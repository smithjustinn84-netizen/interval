"""Generates every app icon and launch image from one drawing of the mark.

    uv run --with pillow tools/generate_icons.py

The mark is the workout's phase ring: three round-capped arcs in the phase colours (Get ready, Work,
Rest), with a clock hand pointing up through the gap at the top. Its geometry lives here and in
`shared/src/splash/IntervalMark.kt`, which draws the same mark for the animated intro; keep the two
in step. Everything is laid out on Android's 108-unit adaptive-icon canvas.
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent

# Geometry, in units of the 108 x 108 canvas. Angles are degrees clockwise from 12 o'clock.
CANVAS = 108
CENTER = CANVAS / 2
RING_RADIUS = 24
RING_STROKE = 7
ARCS = [  # (start, end, colour)
    (14, 64, "F2A81D"),  # Get ready: PhaseColors.prep
    (93, 227, "FF5A43"),  # Work: PhaseColors.work
    (256, 346, "2FD3A0"),  # Rest: PhaseColors.rest
]
HAND_LENGTH = 15
HAND_STROKE = 4.5
HUB_RADIUS = 4.5
PIN_RADIUS = 1.7  # The hole through the hub
INK = "F1F4F8"  # PhaseColors.onGround
GROUND = "0B0D10"  # PhaseColors.ground
GROUND_GLOW = "1A2029"  # The lighter centre of the icon's background

# Grey levels for iOS's tinted icon, which tints by luminance: the phases stay tellable apart.
TINTED_ARCS = ["C8C8C8", "FFFFFF", "9A9A9A"]

SUPERSAMPLE = 4


def point(angle, radius):
    a = math.radians(angle)
    return CENTER + radius * math.sin(a), CENTER - radius * math.cos(a)


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def arc_path(start, end):
    x0, y0 = point(start, RING_RADIUS)
    x1, y1 = point(end, RING_RADIUS)
    large = 1 if end - start > 180 else 0
    return f"M{fmt(x0)},{fmt(y0)} A{RING_RADIUS},{RING_RADIUS} 0 {large},1 {fmt(x1)},{fmt(y1)}"


# From the hub's rim, so the hole through the hub stays open.
HAND_PATH = f"M{fmt(CENTER)},{fmt(CENTER - HUB_RADIUS)} V{fmt(CENTER - HAND_LENGTH)}"


def circle_path(r):
    return f"M{fmt(CENTER - r)},{fmt(CENTER)} a{r},{r} 0 1,0 {fmt(2 * r)},0 a{r},{r} 0 1,0 {fmt(-2 * r)},0 Z"


HUB_PATH = circle_path(HUB_RADIUS) + " " + circle_path(PIN_RADIUS)


def mark_paths(arc_colors, ink):
    """The mark as Android vector paths, one stroke per arc, the hand and the hub."""
    out = []
    for (start, end, _), color in zip(ARCS, arc_colors):
        out.append(stroke(arc_path(start, end), color, RING_STROKE))
    out.append(stroke(HAND_PATH, ink, HAND_STROKE))
    out.append(f'    <path android:fillColor="#{ink}" android:fillType="evenOdd" android:pathData="{HUB_PATH}"/>')
    return "\n".join(out)


def stroke(path, color, width):
    return (
        f'    <path android:pathData="{path}" android:strokeColor="#{color}"\n'
        f'          android:strokeWidth="{width}" android:strokeLineCap="round"/>'
    )


def vector(body, size_dp=CANVAS, extra_ns=""):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/generate_icons.py. Edit the script, not this file. -->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
        f'        android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
        f'        android:viewportWidth="{CANVAS}" android:viewportHeight="{CANVAS}">\n'
        f"{body}\n"
        "</vector>\n"
    )


def background_vector():
    """Ground with a soft glow behind the ring, so the icon has depth on a dark wallpaper."""
    body = f"""    <path android:pathData="M0,0h{CANVAS}v{CANVAS}h-{CANVAS}z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{fmt(CENTER)}" android:centerY="{fmt(CENTER)}"
                      android:gradientRadius="{fmt(CENTER)}">
                <item android:offset="0" android:color="#FF{GROUND_GLOW}"/>
                <item android:offset="1" android:color="#FF{GROUND}"/>
            </gradient>
        </aapt:attr>
    </path>"""
    return vector(body, extra_ns='\n        xmlns:aapt="http://schemas.android.com/aapt"')


def desktop_vector(mark):
    """A rounded square, inset as macOS and Windows draw app icons, holding [mark] (vector paths)."""
    inset, corner = 6, 22
    side = CANVAS - 2 * inset
    straight = side - 2 * corner
    tile = (
        f"M{inset + corner},{inset} h{straight} a{corner},{corner} 0 0,1 {corner},{corner} "
        f"v{straight} a{corner},{corner} 0 0,1 -{corner},{corner} h-{straight} "
        f"a{corner},{corner} 0 0,1 -{corner},-{corner} v-{straight} "
        f"a{corner},{corner} 0 0,1 {corner},-{corner} Z"
    )
    body = f'    <path android:fillColor="#{GROUND}" android:pathData="{tile}"/>\n'
    return vector(body + mark)


# Raster ----------------------------------------------------------------------------------------


def rgba(hex_color, alpha=255):
    return tuple(int(hex_color[i : i + 2], 16) for i in (0, 2, 4)) + (alpha,)


def draw_mark(img, scale, arc_colors, ink):
    """Draws the mark onto [img] (supersampled), centred, with [scale] pixels per canvas unit."""
    d = ImageDraw.Draw(img)
    cx, cy = img.width / 2, img.height / 2

    def px(x, y):
        return cx + (x - CENTER) * scale, cy + (y - CENTER) * scale

    def dot(x, y, r, color):
        x, y = px(x, y)
        d.ellipse([x - r * scale, y - r * scale, x + r * scale, y + r * scale], fill=color)

    for (start, end, _), color in zip(ARCS, arc_colors):
        c = rgba(color)
        box = [*px(CENTER - RING_RADIUS - RING_STROKE / 2, CENTER - RING_RADIUS - RING_STROKE / 2),
               *px(CENTER + RING_RADIUS + RING_STROKE / 2, CENTER + RING_RADIUS + RING_STROKE / 2)]
        # Pillow's angles run clockwise from 3 o'clock.
        d.arc(box, start - 90, end - 90, fill=c, width=round(RING_STROKE * scale))
        for a in (start, end):  # Round caps
            dot(*point(a, RING_RADIUS), RING_STROKE / 2, c)
    c = rgba(ink)
    x0, y0 = px(CENTER, CENTER)
    x1, y1 = px(CENTER, CENTER - HAND_LENGTH)
    d.rectangle([x0 - HAND_STROKE / 2 * scale, y1, x0 + HAND_STROKE / 2 * scale, y0], fill=c)
    dot(CENTER, CENTER - HAND_LENGTH, HAND_STROKE / 2, c)
    dot(CENTER, CENTER, HUB_RADIUS, c)
    dot(CENTER, CENTER, PIN_RADIUS, (0, 0, 0, 0))  # Draw replaces pixels, so this punches a hole


def ground_image(size):
    """The ground with the same radial glow as the Android background, across the whole square."""
    img = Image.new("RGBA", (size, size))
    inner, outer = rgba(GROUND_GLOW), rgba(GROUND)
    half = size / 2
    px = img.load()
    for y in range(size):
        for x in range(size):
            t = min(1.0, math.hypot(x + 0.5 - half, y + 0.5 - half) / half)
            px[x, y] = tuple(round(inner[i] + (outer[i] - inner[i]) * t) for i in range(4))
    return img


def render(size, mark_scale, arc_colors=None, ink=INK, background=True, draw=draw_mark):
    """A [size]px square with the mark ([draw]) [mark_scale] times its size on the 108 canvas."""
    arc_colors = arc_colors or [c for _, _, c in ARCS]
    big = size * SUPERSAMPLE
    layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw(layer, big / CANVAS * mark_scale, arc_colors, ink)
    layer = layer.resize((size, size), Image.LANCZOS)
    if not background:
        return layer
    base = ground_image(size)
    base.alpha_composite(layer)
    return base


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(ROOT))


def save(path, img):
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)
    print("wrote", path.relative_to(ROOT))


def main():
    colors = [c for _, _, c in ARCS]
    res = ROOT / "androidApp/res"
    write(res / "drawable/ic_launcher_foreground.xml", vector(mark_paths(colors, INK)))
    write(res / "drawable/ic_launcher_monochrome.xml", vector(mark_paths([INK] * 3, INK)))
    write(res / "drawable/ic_launcher_background.xml", background_vector())

    write(ROOT / "shared/composeResources/drawable/app_icon.xml", desktop_vector(mark_paths(colors, INK)))

    # iOS draws icons full bleed and rounds the corners itself, so the mark can sit larger than on
    # Android, whose launchers crop the 108 canvas to its middle 72.
    ios_scale = 1.3
    ios_icons(ROOT / "iosApp/src/Assets.xcassets", ios_scale, draw_mark)

    # The launch screen's mark, matching the first frame of the intro: the 108 canvas at 288 pt,
    # as Android's splash screen draws its icon.
    launch = ROOT / "iosApp/src/Assets.xcassets/LaunchMark.imageset"
    for factor in (1, 2, 3):
        suffix = "" if factor == 1 else f"@{factor}x"
        save(launch / f"launch-mark{suffix}.png", render(288 * factor, 1.0, background=False))


def ios_icons(catalog, scale, draw):
    """The light, dark and tinted 1024 px app icons into [catalog]'s AppIcon set."""
    icons = catalog / "AppIcon.appiconset"
    # The App Store rejects an icon with an alpha channel.
    save(icons / "app-icon-1024.png", render(1024, scale, draw=draw).convert("RGB"))
    save(icons / "app-icon-1024-dark.png", render(1024, scale, background=False, draw=draw))
    save(icons / "app-icon-1024-tinted.png",
         render(1024, scale, arc_colors=TINTED_ARCS, ink="FFFFFF", background=False, draw=draw))


if __name__ == "__main__":
    main()
